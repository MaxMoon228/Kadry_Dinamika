/**
 * RAW SOURCE RECORDS — строки исходных таблиц в том виде, как они описаны в Приложении 1
 * («Описание данных», выборка Департамента образования и науки Москвы за 2022–2024 гг.).
 *
 * Названия колонок сохранены как в источнике. Все значения — строки или null: типизация,
 * нормализация и дедупликация выполняются в ETL (см. src/data/adapters/normalize.ts
 * и docs/DATA_INTEGRATION_PLAN.md).
 *
 * Колонка «Год» в описании источника отсутствует явно: предполагается, что год среза
 * определяется выгрузкой (файл/лист на год). Требует подтверждения на реальных данных.
 */

/** Таблица 1. «Учителя». Одна строка = педагог × предмет × параллель. */

export interface RawTeacherRow {
  Год: string;
  Идентификатор: string;
  "Краткое наименование образовательной организации": string;
  "Основная должность": string | null;
  "Направление деятельности": string | null;
  Пол: string | null;
  Возраст: string | null;
  "Учёная степень": string | null;
  "Квалификационная категория": string | null;
  "Дата присвоения квалификационной категории": string | null;
  "Срок действия квалификационной категории": string | null;
  "Общий стаж работы": string | null;
  "Стаж педагогической работы": string | null;
  Предмет: string | null;
  Параллель: string | null;
  /** Значение специальности предпроф. класса (например, «IT-вертикаль») либо пусто. */
  "Преподаёт в предпрофессиональных классах": string | null;
  /** «Да» / «Нет». */
  "Имеет классное руководство": string | null;
}

/** Таблица 2. «Образование». Записи дублируются накопительным итогом из года в год. */

export interface RawEducationRow {
  Год: string;
  Идентификатор: string;
  "Тип образования": string | null;
  "Наименование учебного заведения": string | null;
  "Дата окончания": string | null;
  Специализация: string | null;
  Квалификация: string | null;
}

/** Таблица 3. «Повышение квалификации». */

export interface RawTrainingRow {
  Год: string;
  Идентификатор: string;
  "Наименование программы": string | null;
  /** «ПК» или «ПП». */
  "Программа профессиональной переподготовки (ПП) или программа повышения квалификации (ПК)":
    | string
    | null;
  "Организатор программы": string | null;
  "Количество часов": string | null;
  "Дата получения документа": string | null;
}

/** Таблица 4. «Школы». */

export interface RawSchoolRow {
  Год: string;
  Школа: string;
  Округ: string | null;
  "Количество зданий": string | null;
  "Общая численность контингента": string | null;
}

export interface RawDataset {
  teachers: RawTeacherRow[];
  education: RawEducationRow[];
  training: RawTrainingRow[];
  schools: RawSchoolRow[];
}
